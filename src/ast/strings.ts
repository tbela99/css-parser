/**
 * String table of an arena.
 *
 * The strings of the nodes (selectors, names, identifiers, strings, units, ...) are interned: a node stores a string id.
 * An interned string is not necessarily a string object, it is a range of a text:
 *
 * - a range of the content of a source file (`source.content`): the values of the tokens read by the tokenizer. the
 *   table stores the source index and the start and end offsets, no string is created
 * - a range of the canonical text (see {@link canonicalText}): the spelling of the known units and function names
 * - a range of the pool: the code units of the strings that are not a range of a source (decoded escape sequences,
 *   the values parsed from a string by `parseString()`) are copied to the pool
 * - a string: the strings interned by {@link StringTable.intern} (generated by the minifier, the visitors, ...) are
 *   kept as they are
 *
 * The table is keyed by the hash of the code units: a string and a range with the same content have the same id.
 * When the hashes are equal, the code units are compared. The strings are created when they are read
 * ({@link StringTable.get}), once per id.
 *
 * @module
 * @internal
 */
import { type CodeUnits, fromCodes, hashRange, hashString } from "../parser/utils/codes.ts";
import { canonicalCodes, canonicalText } from "../parser/utils/canonical.ts";
import { type SourceText, Utf8Text } from "../parser/input.ts";

/**
 * where the code units of an interned string are stored. a value that is not negative is the index of a source
 * (see {@link StringTable.setText})
 */
export const enum StringSource {
    /**
     * the code units are copied to the pool
     */
    Pool = -1,
    /**
     * range of the canonical text
     */
    Canonical = -2,
    /**
     * a string
     */
    Value = -3,
}

/**
 * boolean properties of the strings computed once per string id, see {@link StringTable.flag}. 4 flags at most
 */
export const enum StringFlag {
    /**
     * the string is a named color, a system color or `currentcolor` / `transparent`, ignoring the case
     */
    Color = 0,
    /**
     * a rule selector that is not modified by the minifier (see `isSimpleSelector()`)
     */
    SimpleSelector = 1,
    /**
     * a rule selector that contains a vendor prefixed pseudo class (see `selectorPrefixes()`)
     */
    VendorPrefix = 2,
}

/**
 * values derived from the strings computed once per string id, see {@link StringTable.derived}
 */
export const enum StringDerived {
    /**
     * the validation syntax of a function (`name()`)
     */
    FunctionSyntax = 0,
    /**
     * the validation syntax of a selector function (`:name()`)
     */
    SelectorFunctionSyntax = 1,
    /**
     * the kind of a transform function name or of a transform property name (see `transformKind()`)
     */
    TransformKind = 2,
    /**
     * true if the rules are allowed in the block of an at-rule (by name, without `@`), see `parseSelector()`
     */
    AtRuleAcceptsRules = 3,
}

/**
 * structured-cloneable copy of a string table, see {@link StringTable.export}
 */
export interface StringTableData {
    /**
     * number of strings
     */
    count: number;
    /**
     * hash of each string
     */
    hashes: Int32Array;
    /**
     * source of each string: the index of its text in {@link texts}
     */
    sources: Int32Array;
    /**
     * start offset of each string in its source
     */
    starts: Int32Array;
    /**
     * end offset of each string in its source
     */
    ends: Int32Array;
    /**
     * text of each source, by source index
     */
    texts: Array<string | Uint8Array>;
    /**
     * code units of the pool
     */
    pool: Uint16Array;
    /**
     * the strings of the `StringSource.Value` entries, by id
     */
    values: Array<string | undefined>;
}



/**
 * builds a string from code units, strings and interned strings, then interns it: no string is created
 *
 * @internal
 */
export class StringBuilder {
    /**
     * code units
     */
    codes: Uint16Array = new Uint16Array(256);
    /**
     * number of code units
     */
    length: number = 0;

    /**
     * drop the code units
     */
    reset(): this {
        this.length = 0;
        return this;
    }

    /**
     * append the code units of an interned string
     * @param table
     * @param id
     */
    appendId(table: StringTable, id: number): this {
        const length: number = table.length(id);

        this.reserve(length);
        this.length += table.copy(id, this.codes, this.length);
        return this;
    }

    /**
     * append a string
     * @param str
     */
    appendString(str: string): this {
        this.reserve(str.length);

        const codes: Uint16Array = this.codes;
        let length: number = this.length;

        for (let i: number = 0; i < str.length; i++) {
            codes[length++] = str.charCodeAt(i);
        }

        this.length = length;
        return this;
    }

    /**
     * append a code unit
     * @param code
     */
    appendCode(code: number): this {
        this.reserve(1);
        this.codes[this.length++] = code;
        return this;
    }

    /**
     * intern the string
     * @param table
     */
    intern(table: StringTable): number {
        return table.internRange(this.codes, 0, this.length, StringSource.Pool);
    }

    /**
     * make room for more code units
     * @param size
     */
    private reserve(size: number): void {
        if (this.length + size > this.codes.length) {
            const codes: Uint16Array = new Uint16Array(Math.max(this.codes.length * 2, this.length + size));

            codes.set(this.codes.subarray(0, this.length));
            this.codes = codes;
        }
    }
}

/**
 * interned strings of an arena
 *
 * @internal
 */
export class StringTable {
    /**
     * An instance is kept alive: the hidden class of the instances would otherwise be collected by a full garbage
     * collection when no instance is alive, and the optimized code that depends on it discarded (deoptimized)
     */
    static readonly shape: StringTable = new StringTable();

    /**
     * number of strings
     */
    count: number = 0;
    /**
     * strings by id: the strings that have been read (see {@link get}) and the `StringSource.Value` strings
     */
    cache: Array<string | undefined> = [];
    /**
     * identity of the ids: replaced when the ids change (see {@link compact}). the caches keyed by string ids use it
     * as a key
     */
    epoch: object = {};
    /**
     * hash of each string
     */
    private hashes: Int32Array = new Int32Array(256);
    /**
     * source of each string, see {@link StringSource}
     */
    private sources: Int32Array = new Int32Array(256);
    /**
     * start of each string in its source
     */
    private starts: Int32Array = new Int32Array(256);
    /**
     * end of each string in its source
     */
    private ends: Int32Array = new Int32Array(256);
    /**
     * hash table: string id + 1 by slot, 0 when the slot is empty (open addressing, linear probing). the load factor
     * is at most 0.5
     */
    private slots: Int32Array = new Int32Array(512);
    /**
     * text of the sources, by source index. utf-8 sources: an empty string, the text is read from the bytes (see
     * {@link utf8})
     */
    private texts: string[] = [];
    /**
     * the utf-8 sources, by source index: the strings are read from the bytes. the strings and the utf-8 sources are
     * not mixed in {@link texts}: the methods of the strings are called on strings only
     */
    private utf8: Array<Uint8Array | undefined> = [];
    /**
     * the converters of the byte offsets of the utf-8 sources to utf-16 offsets, by source index
     */
    private utf8Texts: Array<Utf8Text | undefined> = [];
    /**
     * code units of the sources being tokenized, by source index
     */
    private codes: Array<CodeUnits | undefined> = [];
    /**
     * values derived from the strings, by slot and by id (see {@link derived})
     */
    private derivedValues: Array<Map<number, unknown> | undefined> = [];
    /**
     * properties of the strings, by id (see {@link flag})
     */
    private flags: Uint8Array = new Uint8Array(0);
    /**
     * id of the lowercase string + 1, by id. 0 when it is not computed (see {@link lower})
     */
    private lowers: Int32Array = new Int32Array(0);
    /**
     * builder of the lowercase strings
     */
    private readonly builder: StringBuilder = new StringBuilder();
    /**
     * code units of the strings that are not a range of a source
     */
    private pool: Uint16Array = new Uint16Array(1024);
    /**
     * used length of the pool
     */
    private poolLength: number = 0;

    /**
     * set the text of a source: the strings of the source are ranges of the text
     * @param source source index
     * @param text content of the source
     * @param codes code units of the text, while the source is tokenized: the ranges are compared with the code units
     * (faster than the text). see {@link releaseCodes}
     */
    setText(source: number, text: SourceText, codes: CodeUnits | null = null): void {
        if (typeof text === "string") {
            this.texts[source] = text;
            this.utf8[source] = undefined;
            this.utf8Texts[source] = undefined;
        } else {
            this.texts[source] = "";
            this.utf8[source] = text.bytes;
            this.utf8Texts[source] = text;
        }

        this.codes[source] = codes ?? undefined;
    }

    /**
     * the utf-16 offset of an offset of a source: the offsets of utf-8 sources are byte offsets
     * @param source source index
     * @param offset
     */
    utf16Offset(source: number, offset: number): number {
        const text: Utf8Text | undefined = this.utf8Texts[source];

        return text === undefined ? offset : text.utf16(offset);
    }

    /**
     * code unit of the text of a source, NaN after its end
     * @param source source index
     * @param offset
     */
    sourceCodeAt(source: number, offset: number): number {
        const bytes: Uint8Array | undefined = this.utf8[source];

        if (bytes !== undefined) {
            return bytes[offset] ?? NaN;
        }

        const text: string | undefined = this.texts[source];

        if (text !== undefined && offset < text.length) {
            return text.charCodeAt(offset);
        }

        return this.codes[source]?.[offset] ?? NaN;
    }

    /**
     * drop the code units of a source: the source is no longer tokenized, see {@link setText}
     * @param source
     */
    releaseCodes(source: number): void {
        this.codes[source] = undefined;
    }

    /**
     * intern a string
     * @param str
     * @returns the string id
     */
    intern(str: string): number {
        if (typeof str !== "string") {
            str = String(str);
        }

        const hash: number = hashString(str);
        const mask: number = this.slots.length - 1;
        let slot: number = hash & mask;
        let entry: number;

        while ((entry = this.slots[slot]) !== 0) {
            if (this.hashes[entry - 1] === hash && this.equalsString(entry - 1, str)) {
                return entry - 1;
            }

            slot = (slot + 1) & mask;
        }

        // the string is kept
        const id: number = this.add(hash, slot, StringSource.Value, 0, str.length);

        this.cache[id] = str;
        return id;
    }

    /**
     * intern a range of code units
     * @param codes code units
     * @param start
     * @param end
     * @param source where the range is stored when it is interned: the index of the source the code units are read
     * from (the range is kept), `StringSource.Canonical` (the code units are the canonical text) or `StringSource.Pool`
     * (the code units are copied)
     * @returns the string id
     */
    internRange(codes: CodeUnits, start: number, end: number, source: number): number {
        const hash: number = hashRange(codes, start, end);
        const mask: number = this.slots.length - 1;
        let slot: number = hash & mask;
        let entry: number;

        while ((entry = this.slots[slot]) !== 0) {
            if (this.hashes[entry - 1] === hash && this.equalsRange(entry - 1, codes, start, end)) {
                return entry - 1;
            }

            slot = (slot + 1) & mask;
        }

        if (source !== StringSource.Pool) {
            return this.add(hash, slot, source, start, end);
        }

        // copy the code units to the pool
        const length: number = end - start;

        if (this.poolLength + length > this.pool.length) {
            let size: number = this.pool.length * 2;

            while (size < this.poolLength + length) {
                size *= 2;
            }

            const pool: Uint16Array = new Uint16Array(size);

            pool.set(this.pool.subarray(0, this.poolLength));
            this.pool = pool;
        }

        const pool: Uint16Array = this.pool;
        const offset: number = this.poolLength;

        for (let i: number = 0; i < length; i++) {
            pool[offset + i] = codes[start + i];
        }

        this.poolLength += length;

        return this.add(hash, slot, StringSource.Pool, offset, offset + length);
    }

    /**
     * id of a string, -1 when the string is not interned
     * @param str
     */
    lookup(str: string): number {
        const hash: number = hashString(str);
        const mask: number = this.slots.length - 1;
        let slot: number = hash & mask;
        let entry: number;

        while ((entry = this.slots[slot]) !== 0) {
            if (this.hashes[entry - 1] === hash && this.equalsString(entry - 1, str)) {
                return entry - 1;
            }

            slot = (slot + 1) & mask;
        }

        return -1;
    }

    /**
     * the string of an id. the string is created the first time it is read
     * @param id
     */
    get(id: number): string {
        let str: string | undefined = this.cache[id];

        if (str === undefined && id < this.count) {
            const source: number = this.sources[id];

            const bytes: Uint8Array | undefined = source >= 0 ? this.utf8[source] : undefined;

            str =
                source === StringSource.Pool
                    ? fromCodes(this.pool, this.starts[id], this.ends[id])
                    : bytes !== undefined
                      ? fromCodes(bytes, this.starts[id], this.ends[id])
                      : (source === StringSource.Canonical ? canonicalText() : this.texts[source]).slice(
                            this.starts[id],
                            this.ends[id],
                        );

            this.cache[id] = str;
        }

        return str as string;
    }

    /**
     * length of a string
     * @param id
     */
    length(id: number): number {
        return this.ends[id] - this.starts[id];
    }

    /**
     * code unit of a string
     * @param id
     * @param index
     */
    codeAt(id: number, index: number): number {
        const source: number = this.sources[id];
        const offset: number = this.starts[id] + index;

        if (source >= 0) {
            const bytes: Uint8Array | undefined = this.utf8[source];

            return bytes === undefined ? this.texts[source].charCodeAt(offset) : bytes[offset];
        }

        switch (source) {
            case StringSource.Pool:
                return this.pool[offset];
            case StringSource.Canonical:
                return canonicalText().charCodeAt(offset);
            default:
                return (this.cache[id] as string).charCodeAt(index);
        }
    }

    /**
     * copy the code units of a string to a buffer. the string is not created
     * @param id
     * @param target
     * @param offset offset in the target
     * @returns the number of code units
     */
    copy(id: number, target: Uint16Array, offset: number): number {
        const source: number = this.sources[id];
        const start: number = this.starts[id];
        const length: number = this.ends[id] - start;

        if (source === StringSource.Pool) {
            target.set(this.pool.subarray(start, start + length), offset);
        } else if (source === StringSource.Canonical) {
            target.set(canonicalCodes().subarray(start, start + length), offset);
        } else if (source >= 0 && this.utf8[source] !== undefined) {
            target.set((this.utf8[source] as Uint8Array).subarray(start, start + length), offset);
        } else {
            const text: string = source === StringSource.Value ? (this.cache[id] as string) : this.texts[source];
            const base: number = source === StringSource.Value ? 0 : start;

            for (let i: number = 0; i < length; i++) {
                target[offset + i] = text.charCodeAt(base + i);
            }
        }

        return length;
    }

    /**
     * a boolean property of a string, computed once per id: the string is read once (see {@link StringFlag})
     * @param id
     * @param flag
     * @param compute computes the property from the string
     */
    flag(id: number, flag: StringFlag, compute: (str: string) => boolean): boolean {
        if (id >= this.flags.length) {
            const flags: Uint8Array = new Uint8Array(Math.max(this.count, id + 1) * 2);

            flags.set(this.flags);
            this.flags = flags;
        }

        // 2 bits by flag: computed, value
        const shift: number = flag * 2;
        let value: number = (this.flags[id] >> shift) & 3;

        if (value === 0) {
            value = compute(this.get(id)) ? 3 : 1;
            this.flags[id] |= value << shift;
        }

        return value === 3;
    }

    /**
     * a boolean property of a string, computed once per id from the string id (the string is not necessarily read),
     * see {@link flag}
     * @param id
     * @param flag
     * @param compute computes the property from the string id
     */
    flagId(id: number, flag: StringFlag, compute: (id: number) => boolean): boolean {
        if (id >= this.flags.length) {
            const flags: Uint8Array = new Uint8Array(Math.max(this.count, id + 1) * 2);

            flags.set(this.flags);
            this.flags = flags;
        }

        const shift: number = flag * 2;
        let value: number = (this.flags[id] >> shift) & 3;

        if (value === 0) {
            value = compute(id) ? 3 : 1;
            this.flags[id] |= value << shift;
        }

        return value === 3;
    }

    /**
     * a value derived from a string, computed once per id (see {@link StringDerived})
     * @param id
     * @param slot
     * @param compute computes the value from the string id
     */
    derived<T>(id: number, slot: StringDerived, compute: (id: number) => T): T {
        let values: Map<number, unknown> | undefined = this.derivedValues[slot];

        if (values === undefined) {
            values = this.derivedValues[slot] = new Map();
        }

        let value: T | undefined = values.get(id) as T | undefined;

        if (value === undefined && !values.has(id)) {
            value = compute(id);
            values.set(id, value);
        }

        return value as T;
    }

    /**
     * copy the code units of a string to a byte buffer when they are all ascii (UTF-8 encoding). the string is not
     * created
     * @param id
     * @param target
     * @param offset offset in the target. the target has room for the string
     * @returns the number of bytes, -1 when the string is not ascii
     */
    copyAscii(id: number, target: Uint8Array, offset: number): number {
        const source: number = this.sources[id];
        const start: number = this.starts[id];
        const length: number = this.ends[id] - start;
        let code: number;

        if (source === StringSource.Pool || source === StringSource.Canonical) {
            const codes: Uint16Array = source === StringSource.Pool ? this.pool : canonicalCodes();

            for (let i: number = 0; i < length; i++) {
                if ((code = codes[start + i]) > 0x7f) {
                    return -1;
                }

                target[offset + i] = code;
            }
        } else if (source >= 0 && this.utf8[source] !== undefined) {
            const bytes: Uint8Array = this.utf8[source] as Uint8Array;

            for (let i: number = 0; i < length; i++) {
                if ((code = bytes[start + i]) > 0x7f) {
                    return -1;
                }

                target[offset + i] = code;
            }
        } else {
            const text: string = source === StringSource.Value ? (this.cache[id] as string) : this.texts[source];
            const base: number = source === StringSource.Value ? 0 : start;

            for (let i: number = 0; i < length; i++) {
                if ((code = text.charCodeAt(base + i)) > 0x7f) {
                    return -1;
                }

                target[offset + i] = code;
            }
        }

        return length;
    }

    /**
     * index of the first occurrence of a code unit in a string, -1 when it is not found. the string is not created
     * @param id
     * @param code
     */
    indexOfCode(id: number, code: number): number {
        const source: number = this.sources[id];
        const start: number = this.starts[id];
        const length: number = this.ends[id] - start;

        if (source === StringSource.Pool || source === StringSource.Canonical) {
            const codes: Uint16Array = source === StringSource.Pool ? this.pool : canonicalCodes();

            for (let i: number = 0; i < length; i++) {
                if (codes[start + i] === code) {
                    return i;
                }
            }

            return -1;
        }

        if (source >= 0 && this.utf8[source] !== undefined) {
            const bytes: Uint8Array = this.utf8[source] as Uint8Array;

            for (let i: number = 0; i < length; i++) {
                if (bytes[start + i] === code) {
                    return i;
                }
            }

            return -1;
        }

        const text: string = source === StringSource.Value ? (this.cache[id] as string) : this.texts[source];
        const base: number = source === StringSource.Value ? 0 : start;

        for (let i: number = 0; i < length; i++) {
            if (text.charCodeAt(base + i) === code) {
                return i;
            }
        }

        return -1;
    }

    /**
     * true if the string of an id equals a string. the string is not created
     * @param id
     * @param str
     */
    equals(id: number, str: string): boolean {
        const cached: string | undefined = this.cache[id];

        if (cached !== undefined) {
            return cached === str;
        }

        if (id >= this.count || this.length(id) !== str.length) {
            return false;
        }

        for (let i: number = 0; i < str.length; i++) {
            if (this.codeAt(id, i) !== str.charCodeAt(i)) {
                return false;
            }
        }

        return true;
    }

    /**
     * id of the lowercase string (like `toLowerCase()`): the id itself when the string has no uppercase letter. the
     * string is not created when it is ascii
     * @param id
     */
    lower(id: number): number {
        if (id < this.lowers.length && this.lowers[id] !== 0) {
            return this.lowers[id] - 1;
        }

        const length: number = this.length(id);
        let result: number = id;

        for (let i: number = 0; i < length; i++) {
            const code: number = this.codeAt(id, i);

            if (code > 0x7f) {
                // unicode case mapping
                const str: string = this.get(id);
                const lower: string = str.toLowerCase();

                result = lower === str ? id : this.intern(lower);
                break;
            }

            if (code >= 0x41 && code <= 0x5a) {
                // ascii: lowercased in the builder
                const builder: StringBuilder = this.builder.reset();

                builder.appendId(this, id);

                const codes: Uint16Array = builder.codes;

                for (let k: number = i; k < length; k++) {
                    if (codes[k] >= 0x41 && codes[k] <= 0x5a) {
                        codes[k] += 32;
                    }
                }

                result = builder.intern(this);
                break;
            }
        }

        if (id >= this.lowers.length) {
            const lowers: Int32Array = new Int32Array(Math.max(this.count, id + 1) * 2);

            lowers.set(this.lowers);
            this.lowers = lowers;
        }

        this.lowers[id] = result + 1;
        return result;
    }

    /**
     * true if the string of an id starts with a string. the string is not created
     * @param id
     * @param str
     */
    startsWith(id: number, str: string): boolean {
        if (id >= this.count || this.length(id) < str.length) {
            return false;
        }

        for (let i: number = 0; i < str.length; i++) {
            if (this.codeAt(id, i) !== str.charCodeAt(i)) {
                return false;
            }
        }

        return true;
    }

    /**
     * true if the string of an id equals a string, ignoring the case of the ascii letters. the string is not created
     * @param id
     * @param str
     */
    equalsIgnoreCase(id: number, str: string): boolean {
        if (id >= this.count || this.length(id) !== str.length) {
            return false;
        }

        for (let i: number = 0; i < str.length; i++) {
            let a: number = this.codeAt(id, i);
            let b: number = str.charCodeAt(i);

            if (a >= 65 && a <= 90) {
                a += 32;
            }

            if (b >= 65 && b <= 90) {
                b += 32;
            }

            if (a !== b) {
                return false;
            }
        }

        return true;
    }

    /**
     * drop the strings that are not used and renumber the others
     * @param used used strings, by id
     * @returns the new id of each string
     */
    compact(used: Uint8Array): Uint32Array {
        const mapping: Uint32Array = new Uint32Array(this.count);
        const previous: StringTable = this.clone();
        let pool: Uint16Array = new Uint16Array(Math.max(1024, this.poolLength));
        let poolLength: number = 0;
        let count: number = 0;

        for (let id: number = 0; id < previous.count; id++) {
            if (used[id]) {
                mapping[id] = count++;
            }
        }

        this.reset(count);

        for (let id: number = 0; id < previous.count; id++) {
            if (!used[id]) {
                continue;
            }

            const target: number = mapping[id];
            let start: number = previous.starts[id];
            let end: number = previous.ends[id];

            // the pool only keeps the used strings
            if (previous.sources[id] === StringSource.Pool) {
                pool.set(previous.pool.subarray(start, end), poolLength);
                end = poolLength + end - start;
                start = poolLength;
                poolLength = end;
            }

            this.hashes[target] = previous.hashes[id];
            this.sources[target] = previous.sources[id];
            this.starts[target] = start;
            this.ends[target] = end;
            this.cache[target] = previous.cache[id];
        }

        this.pool = pool;
        this.poolLength = poolLength;
        this.texts = previous.texts;
        this.utf8 = previous.utf8;
        this.utf8Texts = previous.utf8Texts;
        this.rehash();

        return mapping;
    }

    /**
     * structured-cloneable copy of the table
     */
    export(): StringTableData {
        const values: Array<string | undefined> = [];

        for (let id: number = 0; id < this.count; id++) {
            if (this.sources[id] === StringSource.Value) {
                values[id] = this.cache[id];
            }
        }

        return {
            count: this.count,
            hashes: this.hashes.slice(0, this.count),
            sources: this.sources.slice(0, this.count),
            starts: this.starts.slice(0, this.count),
            ends: this.ends.slice(0, this.count),
            texts: this.texts.map((text: string, source: number): string | Uint8Array =>
                this.utf8[source] === undefined ? text : (this.utf8[source] as Uint8Array).slice(),
            ),
            pool: this.pool.slice(0, this.poolLength),
            values,
        };
    }

    /**
     * initialize the table from an exported copy
     * @param data
     */
    import(data: StringTableData): void {
        this.reset(data.count);
        this.hashes.set(data.hashes);
        this.sources.set(data.sources);
        this.starts.set(data.starts);
        this.ends.set(data.ends);
        this.texts = [];
        this.utf8 = [];
        this.utf8Texts = [];
        data.texts.forEach((text: string | Uint8Array, source: number): void =>
            this.setText(source, typeof text === "string" ? text : Utf8Text.from(text)),
        );
        this.pool = data.pool.length > 0 ? data.pool.slice() : new Uint16Array(1024);
        this.poolLength = data.pool.length;

        for (let id: number = 0; id < data.count; id++) {
            if (data.sources[id] === StringSource.Value) {
                this.cache[id] = data.values[id];
            }
        }

        this.rehash();
    }

    /**
     * add a string
     * @param hash
     * @param slot empty slot of the hash table
     * @param source
     * @param start
     * @param end
     */
    private add(hash: number, slot: number, source: number, start: number, end: number): number {
        const id: number = this.count++;

        if (id === this.hashes.length) {
            this.grow(id * 2);
        }

        this.hashes[id] = hash;
        this.sources[id] = source;
        this.starts[id] = start;
        this.ends[id] = end;
        this.slots[slot] = id + 1;

        if (this.count * 2 > this.slots.length) {
            this.rehash();
        }

        return id;
    }

    /**
     * true if a string has the code units of a range
     * @param id
     * @param codes
     * @param start
     * @param end
     */
    private equalsRange(id: number, codes: CodeUnits, start: number, end: number): boolean {
        const length: number = end - start;
        const source: number = this.sources[id];
        const offset: number = this.starts[id];

        if (this.ends[id] - offset !== length) {
            return false;
        }

        if (source === StringSource.Pool) {
            const pool: Uint16Array = this.pool;

            for (let i: number = 0; i < length; i++) {
                if (pool[offset + i] !== codes[start + i]) {
                    return false;
                }
            }

            return true;
        }

        if (source === StringSource.Canonical) {
            const canonical: Uint16Array = canonicalCodes();

            for (let i: number = 0; i < length; i++) {
                if (canonical[offset + i] !== codes[start + i]) {
                    return false;
                }
            }

            return true;
        }

        // the source being tokenized (its code units are compared), or a utf-8 source (its bytes are compared)
        const sourceCodes: CodeUnits | undefined =
            source >= 0 ? (this.codes[source] ?? this.utf8[source]) : undefined;

        // the source being tokenized: the code units are compared
        if (sourceCodes !== undefined) {
            for (let i: number = 0; i < length; i++) {
                if (sourceCodes[offset + i] !== codes[start + i]) {
                    return false;
                }
            }

            return true;
        }

        const text: string = source === StringSource.Value ? (this.cache[id] as string) : this.texts[source];

        for (let i: number = 0; i < length; i++) {
            if (text.charCodeAt(offset + i) !== codes[start + i]) {
                return false;
            }
        }

        return true;
    }

    /**
     * true if a string equals a string
     * @param id
     * @param str
     */
    private equalsString(id: number, str: string): boolean {
        const source: number = this.sources[id];

        if (source === StringSource.Value || this.cache[id] !== undefined) {
            return this.cache[id] === str;
        }

        const length: number = str.length;
        const offset: number = this.starts[id];

        if (this.ends[id] - offset !== length) {
            return false;
        }

        if (source === StringSource.Pool) {
            const pool: Uint16Array = this.pool;

            for (let i: number = 0; i < length; i++) {
                if (pool[offset + i] !== str.charCodeAt(i)) {
                    return false;
                }
            }

            return true;
        }

        const bytes: Uint8Array | undefined = source >= 0 ? this.utf8[source] : undefined;

        if (bytes !== undefined) {
            for (let i: number = 0; i < length; i++) {
                if (bytes[offset + i] !== str.charCodeAt(i)) {
                    return false;
                }
            }

            return true;
        }

        const text: string = source === StringSource.Canonical ? canonicalText() : this.texts[source];

        for (let i: number = 0; i < length; i++) {
            if (text.charCodeAt(offset + i) !== str.charCodeAt(i)) {
                return false;
            }
        }

        return true;
    }

    /**
     * grow the columns of the strings
     * @param size
     */
    private grow(size: number): void {
        const grow = (array: Int32Array): Int32Array => {
            const result: Int32Array = new Int32Array(size);

            result.set(array.subarray(0, Math.min(array.length, size)));
            return result;
        };

        this.hashes = grow(this.hashes);
        this.sources = grow(this.sources);
        this.starts = grow(this.starts);
        this.ends = grow(this.ends);
    }

    /**
     * drop the strings, allocate the columns for `count` strings. the ids change
     * @param count
     */
    private reset(count: number): void {
        const size: number = Math.max(256, count);

        this.count = count;
        this.cache = [];
        this.epoch = {};
        this.lowers = new Int32Array(0);
        this.flags = new Uint8Array(0);
        this.derivedValues = [];
        this.hashes = new Int32Array(size);
        this.sources = new Int32Array(size);
        this.starts = new Int32Array(size);
        this.ends = new Int32Array(size);
    }

    /**
     * rebuild the hash table
     */
    private rehash(): void {
        let size: number = 512;

        while (size < this.count * 4) {
            size *= 2;
        }

        const slots: Int32Array = new Int32Array(size);
        const mask: number = size - 1;

        for (let id: number = 0; id < this.count; id++) {
            let slot: number = this.hashes[id] & mask;

            while (slots[slot] !== 0) {
                slot = (slot + 1) & mask;
            }

            slots[slot] = id + 1;
        }

        this.slots = slots;
    }

    /**
     * shallow copy of the table
     */
    private clone(): StringTable {
        const table: StringTable = new StringTable();

        table.count = this.count;
        table.cache = this.cache;
        table.hashes = this.hashes;
        table.sources = this.sources;
        table.starts = this.starts;
        table.ends = this.ends;
        table.texts = this.texts;
        table.utf8 = this.utf8;
        table.utf8Texts = this.utf8Texts;
        table.pool = this.pool;
        table.poolLength = this.poolLength;

        return table;
    }
}
